<#
 STERP acceptance-scenario coverage generator.
 Reads the acceptance scenarios (AC-001..AC-nnn) from section 12 of the functional specification,
 scans every test layer for "AC: AC-nnn" tags (COBOL test drivers, SQL test scripts and .NET
 harness [StTest(Ac="...")] attributes) and writes docs\ACCEPTANCE.md: one row per scenario with
 the layers and the test names that prove it, plus the list of scenarios with no automated test.
 Scenarios that can only be shown by hand are declared in build\ac-manual.txt
 (one "AC-nnn | justification" per line) and reported as manual/UI instead of uncovered.
   ac-coverage.ps1           write the report and list the uncovered scenarios
   ac-coverage.ps1 -Strict   exit 1 if any scenario is neither automated nor justified as manual
#>
param([switch]$Strict)
. "$PSScriptRoot\env.ps1"
Set-Location $STERP_ROOT

if ($env:STERP_SPEC) { $specDir = $env:STERP_SPEC } else { $specDir = Join-Path $STERP_ROOT '..\STERP-Supply-Chain-Functional-Specification' }
$specFile = if (Test-Path $specDir) { Get-ChildItem $specDir -Filter '12-*.md' | Select-Object -First 1 }
if (-not $specFile) { throw "Acceptance scenario specification (12-*.md) not found in $specDir - clone it next to STERP-App or set STERP_SPEC" }

# ---------------------------------------------------------------- scenarios from the specification
$acs = [ordered]@{}
$section = 'Shared controls'
foreach ($l in Get-Content $specFile.FullName) {
    if ($l -match '^##\s+\d+\.\s*(.+?)\s*$') { $section = $Matches[1]; continue }
    if ($l -match '^\|\s*(AC-\d{3})\s+([^|]+?)\s*\|\s*([^|]*)\|') {
        $acs[$Matches[1]] = [pscustomobject]@{
            Id = $Matches[1]; Title = $Matches[2].Trim(); Area = $section
            Reqs = $Matches[3].Trim(); Tests = New-Object System.Collections.Generic.List[object]
        }
    }
}

# ---------------------------------------------------------------- manual / UI declarations
$manual = [ordered]@{}
$manualFile = Join-Path $PSScriptRoot 'ac-manual.txt'
if (Test-Path $manualFile) {
    foreach ($l in Get-Content $manualFile) {
        if ($l -match '^\s*(AC-\d{3})\s*\|\s*(.+?)\s*$') { $manual[$Matches[1]] = $Matches[2] }
    }
}

# ---------------------------------------------------------------- tags in the test layers
$layers = @(
    [pscustomobject]@{ Name = 'COBOL'; Path = 'cobol\tests';          Ext = @('.cob', '.cpy') }
    [pscustomobject]@{ Name = 'SQL';   Path = 'db\tests';             Ext = @('.sql') }
    [pscustomobject]@{ Name = '.NET';  Path = 'dotnet\STERP.Tests';   Ext = @('.cs') }
)
$tagged = 0
foreach ($layer in $layers) {
    $root = Join-Path $STERP_ROOT $layer.Path
    if (-not (Test-Path $root)) { continue }
    foreach ($f in Get-ChildItem $root -Recurse -File | Where-Object { $_.Extension -in $layer.Ext -and $_.FullName -notmatch '\\(obj|bin)\\' }) {
        $rel = $f.FullName.Substring($STERP_ROOT.Length + 1)
        $lines = Get-Content $f.FullName
        for ($i = 0; $i -lt $lines.Count; $i++) {
            $line = $lines[$i]
            $ids = [regex]::Matches($line, 'AC-\d{3}')
            if ($ids.Count -eq 0) { continue }
            # test name: the harness attribute name for .NET, the driver/script name elsewhere
            $name = $f.BaseName
            if ($layer.Name -eq '.NET') {
                $block = ($lines[[Math]::Max(0, $i - 3)..[Math]::Min($lines.Count - 1, $i + 3)] -join ' ')
                if ($block -match 'StTest\(\s*"([^"]+)"') { $name = $Matches[1] }
            } elseif ($layer.Name -eq 'SQL' -and $line -notmatch 'AC:') {
                continue   # narrative prose, not a tag
            }
            foreach ($m in $ids) {
                if (-not $acs.Contains($m.Value)) { continue }
                $entry = "$($layer.Name)|$name|$rel"
                if (-not ($acs[$m.Value].Tests | Where-Object { $_ -eq $entry })) {
                    $acs[$m.Value].Tests.Add($entry) | Out-Null
                    $tagged++
                }
            }
        }
    }
}

# ---------------------------------------------------------------- report
$md = New-Object System.Text.StringBuilder
[void]$md.AppendLine('# STERP - Stefan''s ERP: acceptance scenario coverage')
[void]$md.AppendLine('')
[void]$md.AppendLine("Generated by ``build\ac-coverage.ps1`` on $(Get-Date -Format 'dd/MM/yyyy HH:mm') from the ``AC:`` tags in")
[void]$md.AppendLine('`cobol\tests`, `db\tests` and `dotnet\STERP.Tests`. Do not edit by hand - tag the test instead.')
[void]$md.AppendLine('')
[void]$md.AppendLine('@@SUMMARY@@')

$uncovered = @(); $manualOnly = @(); $automated = 0
$area = ''
foreach ($id in $acs.Keys) {
    $ac = $acs[$id]
    if ($ac.Area -ne $area) {
        $area = $ac.Area
        [void]$md.AppendLine(''); [void]$md.AppendLine("## $area"); [void]$md.AppendLine('')
        [void]$md.AppendLine('| AC | Scenario | Layers | Tests |'); [void]$md.AppendLine('|---|---|---|---|')
    }
    if ($ac.Tests.Count -gt 0) {
        $automated++
        $ls = ($ac.Tests | ForEach-Object { $_.Split('|')[0] } | Sort-Object -Unique) -join ', '
        $ts = (($ac.Tests | ForEach-Object { $_.Split('|')[1] } | Sort-Object -Unique) | ForEach-Object { '`' + $_ + '`' }) -join '<br>'
    } elseif ($manual.Contains($id)) {
        $manualOnly += $id
        $ls = '**manual/UI**'; $ts = $manual[$id]
    } else {
        $uncovered += $id
        $ls = '**NONE**'; $ts = ''
    }
    [void]$md.AppendLine("| $id | $($ac.Title.Replace('|','/')) | $ls | $ts |")
}

if ($uncovered.Count -gt 0) {
    [void]$md.AppendLine(''); [void]$md.AppendLine('## Scenarios with no automated test'); [void]$md.AppendLine('')
    foreach ($id in $uncovered) { [void]$md.AppendLine("* **$id** $($acs[$id].Title)") }
}
if ($manualOnly.Count -gt 0) {
    [void]$md.AppendLine(''); [void]$md.AppendLine('## Scenarios verified manually (declared in `build\ac-manual.txt`)'); [void]$md.AppendLine('')
    foreach ($id in $manualOnly) { [void]$md.AppendLine("* **$id** $($acs[$id].Title) - $($manual[$id])") }
}

$pct = if ($acs.Count) { [Math]::Round(100.0 * ($automated + $manualOnly.Count) / $acs.Count, 1) } else { 0 }
$summary = "**Coverage:** $automated of $($acs.Count) scenarios have at least one automated test; " +
           "$($manualOnly.Count) are declared manual/UI; $($uncovered.Count) are uncovered ($pct% accounted for). " +
           "$tagged test tags found."
[IO.File]::WriteAllText((Join-Path $STERP_ROOT 'docs\ACCEPTANCE.md'), $md.ToString().Replace('@@SUMMARY@@', $summary))

Write-Host "Scenarios: $($acs.Count)  automated: $automated  manual/UI: $($manualOnly.Count)  uncovered: $($uncovered.Count)"
if ($uncovered) { Write-Host "Uncovered: $($uncovered -join ', ')" -ForegroundColor Yellow }
if ($Strict -and $uncovered) { exit 1 }
exit 0
