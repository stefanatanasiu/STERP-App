<#
 STERP source line report - proves the COBOL share of the hand-written code.
 Counts non-blank lines of hand-written code.  Seed DATA (db\seed\**, data\legacy\*.DAT) and
 build output (obj\, bin\) are excluded; WinForms *.Designer.vb files are counted as VB.NET.
   loc-report.ps1             print table, write docs\LOC-REPORT.md
   loc-report.ps1 -Min 70     exit 1 when COBOL share < 70%
#>
param([double]$Min = 0, [switch]$NoWrite)
. "$PSScriptRoot\env.ps1"
Set-Location $STERP_ROOT
$cats = [ordered]@{
    'COBOL programs (.cob)'  = @{ Path = 'cobol'; Ext = '.cob'; Cobol = $true }
    'COBOL copybooks (.cpy)' = @{ Path = 'cobol'; Ext = '.cpy'; Cobol = $true }
    'VB.NET (.vb)'           = @{ Path = 'dotnet'; Ext = '.vb' }
    'C# (.cs)'               = @{ Path = 'dotnet'; Ext = '.cs' }
    'T-SQL (.sql)'           = @{ Path = 'db'; Ext = '.sql' }
    'C (.c/.h)'              = @{ Path = 'c'; Ext = '.c' }
    'Scripts (.ps1/.cmd)'    = @{ Path = '.'; Ext = '.ps1|.cmd' }
}
function Count([string]$path, [string]$ext) {
    $exts = $ext -split '\|'
    $n = 0; $files = 0
    Get-ChildItem $path -Recurse -File | Where-Object {
        $exts -contains $_.Extension.ToLower() -and $_.FullName -notmatch '\\(obj|bin|packages|\.vs)\\' -and
        $_.FullName -notmatch '\\db\\seed\\' -and $_.FullName -notmatch '\\spike\\'
    } | ForEach-Object { $files++; $n += @(Get-Content $_.FullName | Where-Object { $_.Trim() -ne '' }).Count }
    return @($n, $files)
}
$rows = @(); $total = 0; $cob = 0
foreach ($k in $cats.Keys) {
    $c = $cats[$k]
    $r = Count $c.Path $c.Ext
    $rows += [pscustomobject]@{ Category = $k; Files = $r[1]; Lines = $r[0] }
    $total += $r[0]; if ($c.Cobol) { $cob += $r[0] }
}
$pct = if ($total) { [math]::Round(100.0 * $cob / $total, 1) } else { 0 }
$rows | Format-Table -AutoSize | Out-Host
Write-Host "COBOL share: $cob of $total non-blank lines = $pct%"
if (-not $NoWrite) {
    $md = "# STERP - Stefan's ERP: source line report`n`nGenerated by ``build\loc-report.ps1`` on $(Get-Date -Format 'dd/MM/yyyy HH:mm'). Non-blank lines; seed data files excluded.`n`n| Category | Files | Lines |`n|---|---:|---:|`n"
    $rows | ForEach-Object { $md += "| $($_.Category) | $($_.Files) | $($_.Lines) |`n" }
    $md += "| **Total** | | **$total** |`n`n**COBOL share: $pct%** ($cob lines)`n"
    [IO.File]::WriteAllText((Join-Path $STERP_ROOT 'docs\LOC-REPORT.md'), $md)
}
if ($Min -gt 0 -and $pct -lt $Min) { Write-Host "COBOL share $pct% is below the required $Min%" -ForegroundColor Red; exit 1 }
exit 0
