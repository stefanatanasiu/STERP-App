<#
 STERP traceability generator.
 Scans all source for requirement tags "REQ: XXX-nnn" (several IDs may follow, comma or space
 separated) and acceptance tags "AC: AC-nnn" and writes docs\TRACEABILITY.md mapping every
 requirement in the functional specification to the code and tests that implement it.
   trace-gen.ps1            write report; list missing IDs
   trace-gen.ps1 -Strict    exit 1 if any specified requirement has no implementation tag
#>
param([switch]$Strict)
. "$PSScriptRoot\env.ps1"
Set-Location $STERP_ROOT
if ($env:STERP_SPEC) { $spec = $env:STERP_SPEC } else { $spec = Join-Path $STERP_ROOT '..\STERP-Supply-Chain-Functional-Specification' }
if (-not (Test-Path $spec)) { throw "Functional specification not found at $spec - clone it next to STERP-App or set STERP_SPEC" }
$reqs = [ordered]@{}
Get-ChildItem $spec -Filter '*.md' | Where-Object { $_.Name -notlike '12-*' } | ForEach-Object {
    foreach ($l in Get-Content $_.FullName) {
        if ($l -match '^\|\s*((COM|FIN|AR|AP|SO|PO|CST|ITM|KIT|BOM|XMD|RPT)-\d{3})\s*\|\s*([^|]+)\|') {
            $t = $Matches[3].Trim(); if ($t.Length -gt 90) { $t = $t.Substring(0, 87) + '...' }
            $reqs[$Matches[1]] = $t
        }
    }
}
$impl = @{}; $tests = @{}
$srcFiles = Get-ChildItem cobol, dotnet, db, c, jobs -Recurse -File -ErrorAction SilentlyContinue |
    Where-Object { $_.Extension -in '.cob', '.cpy', '.vb', '.cs', '.sql', '.c', '.cmd' -and $_.FullName -notmatch '\\(obj|bin)\\' }
foreach ($f in $srcFiles) {
    $rel = $f.FullName.Substring($STERP_ROOT.Length + 1)
    $isTest = $rel -match '(\\tests\\|STERP\.Tests)'
    $lines = Get-Content $f.FullName
    foreach ($l in $lines) {
        if ($l -match 'REQ:\s*(.+)$') {
            foreach ($m in [regex]::Matches($Matches[1], '(COM|FIN|AR|AP|SO|PO|CST|ITM|KIT|BOM|XMD|RPT)-\d{3}')) {
                $id = $m.Value
                $bucket = if ($isTest) { $tests } else { $impl }
                if (-not $bucket.ContainsKey($id)) { $bucket[$id] = New-Object System.Collections.Generic.HashSet[string] }
                [void]$bucket[$id].Add($rel)
            }
        }
    }
}
$md = New-Object System.Text.StringBuilder
[void]$md.AppendLine('# STERP - Stefan''s ERP: requirements traceability matrix')
[void]$md.AppendLine('')
[void]$md.AppendLine("Generated by ``build\trace-gen.ps1`` on $(Get-Date -Format 'dd/MM/yyyy HH:mm') from ``REQ:`` tags in the source. Do not edit by hand.")
[void]$md.AppendLine('')
$missing = @()
$fam = ''
foreach ($id in $reqs.Keys) {
    $f = $id.Split('-')[0]
    if ($f -ne $fam) {
        $fam = $f
        [void]$md.AppendLine(''); [void]$md.AppendLine("## $fam"); [void]$md.AppendLine('')
        [void]$md.AppendLine('| Requirement | Summary | Implemented in | Tested in |'); [void]$md.AppendLine('|---|---|---|---|')
    }
    $i = if ($impl.ContainsKey($id)) { ($impl[$id] | Sort-Object | ForEach-Object { '`' + $_.Replace('\', '/') + '`' }) -join '<br>' } else { $missing += $id; '**NOT TAGGED**' }
    $t = if ($tests.ContainsKey($id)) { ($tests[$id] | Sort-Object | ForEach-Object { '`' + $_.Replace('\', '/') + '`' }) -join '<br>' } else { '' }
    [void]$md.AppendLine("| $id | $($reqs[$id].Replace('|','/')) | $i | $t |")
}
$covered = $reqs.Count - $missing.Count
$head = "**Coverage:** $covered of $($reqs.Count) requirements have implementation tags; $(@($reqs.Keys | Where-Object { $tests.ContainsKey($_) }).Count) have test tags.`n"
$text = $md.ToString().Replace("Do not edit by hand.`r`n", "Do not edit by hand.`r`n`r`n$head")
[IO.File]::WriteAllText((Join-Path $STERP_ROOT 'docs\TRACEABILITY.md'), $text)
Write-Host "Requirements: $($reqs.Count)  implemented-tagged: $covered  test-tagged: $(@($reqs.Keys | Where-Object { $tests.ContainsKey($_) }).Count)"
if ($missing) { Write-Host "Missing: $($missing -join ', ')" -ForegroundColor Yellow }
if ($Strict -and $missing) { exit 1 }
exit 0
